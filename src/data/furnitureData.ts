// Helper functions
export function getFurnitureById(id: string): FurnitureCatalogItem | undefined {
  return furnitureCatalog.find(item => item.id === id)
}

export function getFurnitureByCategory(category: FurnitureCategory): FurnitureCatalogItem[] {
  return furnitureCatalog.filter(item => item.category === category)
}

export function getFurnitureByStyle(style: FurnitureStyle): FurnitureCatalogItem[] {
  return furnitureCatalog.filter(item => item.style === style)
}

export function searchFurniture(query: string): FurnitureCatalogItem[] {
  const lowerQuery = query.toLowerCase()
  return furnitureCatalog.filter(item =>
    item.name.toLowerCase().includes(lowerQuery) ||
    item.description.toLowerCase().includes(lowerQuery) ||
    item.tags.some(tag => tag.toLowerCase().includes(lowerQuery))
  )
}

export function getCategories(): FurnitureCategory[] {
  const categories = new Set(furnitureCatalog.map(item => item.category))
  return Array.from(categories)
}

export function getStyles(): FurnitureStyle[] {
  const styles = new Set(furnitureCatalog.map(item => item.style))
  return Array.from(styles)
}
