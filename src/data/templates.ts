// Helper functions
export function getTemplateById(id: string): FurnitureTemplate | undefined {
  return roomTemplates.find(t => t.id === id)
}

export function getTemplatesByCategory(category: string): FurnitureTemplate[] {
  return roomTemplates.filter(t => t.category === category)
}

export function instantiateTemplate(templateId: string): FurnitureItem[] {
  const template = getTemplateById(templateId)
  if (!template) return []
  
  return template.items.map(item => ({
    ...item,
    id: generateId(),
    isSelected: false,
  }))
}
